#!/usr/bin/env python3
"""Validate roadmap status and sync the generated status table in its canonical MD."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATUS_PATH = ROOT / "docs" / "roadmap-status.json"
ROADMAP_PATH = ROOT / "docs" / "NORTHSTAR_MASTER_ROADMAP.md"
START = "<!-- ROADMAP_STATUS_START -->"
END = "<!-- ROADMAP_STATUS_END -->"
ALLOWED = {"not_started", "in_progress", "blocked", "done"}
STATE_TEXT = {
    "not_started": "Não iniciado",
    "in_progress": "Em andamento",
    "blocked": "Bloqueado",
    "done": "Concluído",
}
EXPECTED = [f"M{i:02d}" for i in range(12)]
SHA_RE = re.compile(r"^[a-fA-F0-9]{40}$")


class StatusValidationError(ValueError):
    """Roadmap state violates the roadmap data contract."""


def validate_status(data: dict) -> None:
    if data.get("schema_version") != 1:
        raise StatusValidationError("schema_version must equal 1")
    if not isinstance(data.get("project_version"), str) or not data["project_version"]:
        raise StatusValidationError("project_version must be a non-empty string")
    milestones = data.get("milestones")
    if not isinstance(milestones, list) or [m.get("id") for m in milestones] != EXPECTED:
        raise StatusValidationError("Expected unique, ordered milestone IDs M00 through M11")
    for m in milestones:
        mid = m["id"]
        if m.get("status") not in ALLOWED:
            raise StatusValidationError(f"{mid}: invalid status {m.get('status')!r}")
        if not isinstance(m.get("title"), str) or not m["title"]:
            raise StatusValidationError(f"{mid}: title required")
        for key in ("prs", "issues", "evidence"):
            if not isinstance(m.get(key), list) or not all(isinstance(v, str) and v.strip() for v in m[key]):
                raise StatusValidationError(f"{mid}: {key} must be a list of nonempty strings")
        if m["status"] == "done":
            if not m["prs"] or not m["evidence"]:
                raise StatusValidationError(f"{mid}: done requires merged PR and acceptance evidence")
            if not isinstance(m.get("merged_commit"), str) or not SHA_RE.fullmatch(m["merged_commit"]):
                raise StatusValidationError(f"{mid}: done requires actual 40-character merged SHA")
            if not m.get("accepted_at"):
                raise StatusValidationError(f"{mid}: done requires accepted_at")


def render_status(data: dict) -> str:
    rows = [
        "| Milestone | Escopo                              | Status       | Evidência |",
        "| --------- | ----------------------------------- | ------------ | --------- |",
    ]
    for m in data["milestones"]:
        state = STATE_TEXT[m["status"]]
        evidence = "Registrada" if m["status"] == "done" else "Pendente"
        rows.append(f"| {m['id']:<9} | {m['title']:<35} | {state:<12} | {evidence:<9} |")
    return "\n".join(rows)


def update_markdown(original: str, data: dict) -> str:
    if original.count(START) != 1 or original.count(END) != 1:
        raise StatusValidationError("Expected exactly one pair of status markers")
    before, remainder = original.split(START, 1)
    _, after = remainder.split(END, 1)
    return before + START + "\n<!-- This section is generated by scripts/sync_roadmap.py. Do not edit manually. -->\n\n" + render_status(data) + "\n\n" + END + after


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="Rewrite only the generated table")
    group.add_argument("--check", action="store_true", help="Fail if table and status JSON diverge (default)")
    args = parser.parse_args()
    try:
        data = json.loads(STATUS_PATH.read_text(encoding="utf-8"))
        validate_status(data)
        current = ROADMAP_PATH.read_text(encoding="utf-8")
        desired = update_markdown(current, data)
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as exc:
        print(f"Roadmap validation failed: {exc}", file=sys.stderr)
        return 2
    if args.write:
        if current != desired:
            ROADMAP_PATH.write_text(desired, encoding="utf-8")
            print("Roadmap generated status table updated")
        else:
            print("Roadmap already synchronized")
        return 0
    if current != desired:
        print("Roadmap status out of sync; run python scripts/sync_roadmap.py --write", file=sys.stderr)
        return 1
    print("Roadmap status synchronized and validated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
